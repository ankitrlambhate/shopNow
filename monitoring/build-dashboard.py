#!/usr/bin/env python3
"""Generates monitoring/grafana-dashboard-shopnow.yaml (a ConfigMap the Grafana sidecar loads automatically).

Edit the PANELS list below and re-run:  python3 monitoring/build-dashboard.py
"""
import json
import pathlib

DS = {"type": "prometheus", "uid": "prometheus"}  # default data source created by kube-prometheus-stack
NS = '$namespace'


def target(expr, legend=""):
    return {"datasource": DS, "expr": expr, "legendFormat": legend, "refId": "A"}


def stat(pid, title, expr, x, unit="short", thresholds=None):
    return {
        "id": pid, "type": "stat", "title": title, "datasource": DS,
        "gridPos": {"h": 4, "w": 6, "x": x, "y": 0},
        "targets": [target(expr)],
        "fieldConfig": {"defaults": {
            "unit": unit,
            "thresholds": {"mode": "absolute", "steps": thresholds or [{"color": "green", "value": None}]},
        }, "overrides": []},
        "options": {"reduceOptions": {"calcs": ["lastNotNull"]}, "colorMode": "value"},
    }


def series(pid, title, exprs, x, y, unit="short", w=12, h=8):
    targets = []
    for i, (expr, legend) in enumerate(exprs):
        t = target(expr, legend)
        t["refId"] = chr(ord("A") + i)
        targets.append(t)
    return {
        "id": pid, "type": "timeseries", "title": title, "datasource": DS,
        "gridPos": {"h": h, "w": w, "x": x, "y": y},
        "targets": targets,
        "fieldConfig": {"defaults": {"unit": unit, "custom": {"lineWidth": 1, "fillOpacity": 10}}, "overrides": []},
        "options": {"legend": {"displayMode": "list", "placement": "bottom"}, "tooltip": {"mode": "multi"}},
    }


REQ = f'http_requests_total{{namespace="{NS}"}}'
DUR = f'http_request_duration_seconds_bucket{{namespace="{NS}"}}'

PANELS = [
    stat(1, "Backend requests / s", f'sum(rate({REQ}[5m]))', 0, "reqps"),
    stat(2, "Backend 5xx error ratio",
         f'sum(rate(http_requests_total{{namespace="{NS}",status=~"5.."}}[5m])) / sum(rate({REQ}[5m]))', 6, "percentunit",
         [{"color": "green", "value": None}, {"color": "orange", "value": 0.01}, {"color": "red", "value": 0.05}]),
    stat(3, "Backend p95 latency", f'histogram_quantile(0.95, sum by (le) (rate({DUR}[5m])))', 12, "s",
         [{"color": "green", "value": None}, {"color": "orange", "value": 0.3}, {"color": "red", "value": 0.5}]),
    stat(4, "Ready pods", f'sum(kube_pod_status_ready{{namespace="{NS}",condition="true"}})', 18),
    series(5, "Requests per second by route",
           [(f'sum by (route) (rate({REQ}[5m]))', "{{route}}")], 0, 4, "reqps"),
    series(6, "Latency percentiles",
           [(f'histogram_quantile(0.50, sum by (le) (rate({DUR}[5m])))', "p50"),
            (f'histogram_quantile(0.95, sum by (le) (rate({DUR}[5m])))', "p95"),
            (f'histogram_quantile(0.99, sum by (le) (rate({DUR}[5m])))', "p99")], 12, 4, "s"),
    series(7, "Responses by status code",
           [(f'sum by (status) (rate({REQ}[5m]))', "{{status}}")], 0, 12, "reqps"),
    series(8, "Ingress requests by status (edge)",
           [('sum by (status) (rate(nginx_ingress_controller_requests[5m]))', "{{status}}")], 12, 12, "reqps"),
    series(9, "CPU usage by pod",
           [(f'sum by (pod) (rate(container_cpu_usage_seconds_total{{namespace="{NS}",container!=""}}[5m]))', "{{pod}}")],
           0, 20, "short"),
    series(10, "Memory working set by pod",
           [(f'sum by (pod) (container_memory_working_set_bytes{{namespace="{NS}",container!=""}})', "{{pod}}")],
           12, 20, "bytes"),
    series(11, "HPA replicas (current vs max)",
           [(f'kube_horizontalpodautoscaler_status_current_replicas{{namespace="{NS}"}}', "{{horizontalpodautoscaler}} current"),
            (f'kube_horizontalpodautoscaler_spec_max_replicas{{namespace="{NS}"}}', "{{horizontalpodautoscaler}} max")],
           0, 28, "short"),
    series(12, "Container restarts (15m)",
           [(f'sum by (pod) (increase(kube_pod_container_status_restarts_total{{namespace="{NS}"}}[15m]))', "{{pod}}")],
           12, 28, "short"),
]

dashboard = {
    "uid": "shopnow-overview",
    "title": "shopNow - Application Overview",
    "tags": ["shopnow"],
    "timezone": "browser",
    "schemaVersion": 39,
    "version": 1,
    "refresh": "30s",
    "time": {"from": "now-1h", "to": "now"},
    "templating": {"list": [{
        "name": "namespace", "type": "query", "datasource": DS,
        "query": {"query": "label_values(kube_pod_info, namespace)", "refId": "ns"},
        "refresh": 2, "includeAll": False,
        "current": {"text": "shopnow-demo", "value": "shopnow-demo"},
    }]},
    "panels": PANELS,
}

body = json.dumps(dashboard, indent=2)
indented = "\n".join("    " + line for line in body.splitlines())
out = f"""# Generated by monitoring/build-dashboard.py - edit the script, not this file.
apiVersion: v1
kind: ConfigMap
metadata:
  name: shopnow-dashboard
  namespace: monitoring
  labels:
    grafana_dashboard: "1"
data:
  shopnow-overview.json: |-
{indented}
"""
path = pathlib.Path(__file__).with_name("grafana-dashboard-shopnow.yaml")
path.write_text(out)
print(f"Wrote {path} ({len(PANELS)} panels)")
